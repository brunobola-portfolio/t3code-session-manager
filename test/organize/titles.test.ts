import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { isTechnicalTitle, proposeTitle } from "../../src/organize/titles.ts";

// Synthetic transcripts reproducing the measured junk shapes. Nothing here is a real conversation.

const user = (content: unknown, extra: Record<string, unknown> = {}): string =>
  JSON.stringify({ type: "user", message: { role: "user", content }, ...extra });
const assistant = (text: string): string =>
  JSON.stringify({ type: "assistant", message: { role: "assistant", content: [{ type: "text", text }] } });

async function proposed(lines: string[], maxLength = 80): Promise<string | null> {
  const dir = await mkdtemp(join(tmpdir(), "t3sm-titles-"));
  try {
    const f = join(dir, "s.jsonl");
    await writeFile(f, lines.join("\n") + "\n");
    return await proposeTitle(f, { maxLength });
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const cmd = (name: string, args = ""): string =>
  `<command-message>${name.slice(1)}</command-message>\n<command-name>${name}</command-name>\n<command-args>${args}</command-args>`;

test("a slash-command message is skipped in favour of the next real message", async () => {
  const t = await proposed([user(cmd("/model")), assistant("ok"), user("Fix the login redirect loop")]);
  assert.equal(t, "Fix the login redirect loop");
});

test("only slash commands: the title is the first command name", async () => {
  assert.equal(await proposed([user(cmd("/model")), user(cmd("/clear"))]), "/model");
});

test("local command output is not a title", async () => {
  const t = await proposed([user(cmd("/model")), user("<local-command-stdout>Set model</local-command-stdout>"), user("Plan the release")]);
  assert.equal(t, "Plan the release");
});

test("ide blocks are stripped and the real text stays", async () => {
  const t = await proposed([user("<ide_opened_file>The user opened the file C:/work/demo/a.ts in the IDE.</ide_opened_file>\nRename the helper")]);
  assert.equal(t, "Rename the helper");
});

test("an unclosed ide block loses only its own line", async () => {
  const t = await proposed([user("<ide_opened_file>The user opened the file a.ts in the IDE.\nRename the helper")]);
  assert.equal(t, "Rename the helper");
});

test("system-reminder, environment_context and browser_instruction blocks are stripped", async () => {
  const t = await proposed([
    user("<system-reminder>be brief</system-reminder>"),
    user("<environment_context>\n<cwd>C:/work/demo</cwd>\n</environment_context>"),
    user("<browser_instruction>use the tab</browser_instruction>\nOpen the docs page"),
  ]);
  assert.equal(t, "Open the docs page");
});

test("an external block alone is skipped, and removed from mixed text", async () => {
  assert.equal(await proposed([user("[external unsupported block: image]"), user("What does this chart show?")]), "What does this chart show?");
  assert.equal(await proposed([user("[external unsupported block: image] What does this chart show?")]), "What does this chart show?");
});

test("Caveat lines are dropped", async () => {
  const t = await proposed([user("Caveat: The messages below were generated by the user while running local commands."), user("Add a retry")]);
  assert.equal(t, "Add a retry");
});

test("tool results, meta and sidechain records are not user messages", async () => {
  const t = await proposed([
    user([{ type: "tool_result", tool_use_id: "x", content: "output text" }]),
    user("meta text", { isMeta: true }),
    user("sub-agent prompt", { isSidechain: true }),
    user([{ type: "text", text: "Real question" }, { type: "tool_result", tool_use_id: "y", content: "zzz" }]),
  ]);
  assert.equal(t, "Real question");
});

test("compaction summaries, transcript-only records and interrupt markers are not titles", async () => {
  const t = await proposed([
    user("This session is being continued from a previous conversation that ran out of context.", { isCompactSummary: true }),
    user("shown only in the transcript", { isVisibleInTranscriptOnly: true }),
    user("[Request interrupted by user]"),
    user("[Request interrupted by user for tool use]"),
    user("Real message after compact"),
  ]);
  assert.equal(t, "Real message after compact");
  assert.equal(await proposed([user("[Request interrupted by user for tool use]")]), null);
});

test("emoji and right-to-left text are kept, multiline collapses", async () => {
  assert.equal(await proposed([user("Ship it 🚀👩‍💻\n\n  now")]), "Ship it 🚀👩‍💻 now");
  assert.equal(await proposed([user("مرحبا بالعالم")]), "مرحبا بالعالم");
});

test("limit is graphemes, cut in the middle", async () => {
  const t = await proposed([user("a".repeat(200))], 80);
  assert.equal(Array.from(t ?? "").length, 80);
  assert.ok(t?.includes("…"));
  const e = await proposed([user("👩‍💻".repeat(100))], 80);
  assert.equal([...new Intl.Segmenter().segment(e ?? "")].length, 80);
});

test("nothing left gives null", async () => {
  assert.equal(await proposed([user("<ide_opened_file>x</ide_opened_file>"), user("  "), assistant("hi")]), null);
  assert.equal(await proposed([]), null);
});

test("custom-title beats ai-title beats summary beats the first message; the latest of each wins", async () => {
  const base = [user("First message")];
  assert.equal(await proposed([...base, JSON.stringify({ type: "summary", summary: "Sum" })]), "Sum");
  assert.equal(await proposed([...base, JSON.stringify({ type: "summary", summary: "Sum" }), JSON.stringify({ type: "ai-title", aiTitle: "AI one" })]), "AI one");
  assert.equal(
    await proposed([
      JSON.stringify({ type: "custom-title", customTitle: "Mine old" }),
      ...base,
      JSON.stringify({ type: "ai-title", aiTitle: "AI" }),
      JSON.stringify({ type: "custom-title", customTitle: "Mine new" }),
      JSON.stringify({ type: "summary", summary: "Sum" }),
    ]),
    "Mine new",
  );
  assert.equal(await proposed([JSON.stringify({ type: "ai-title", aiTitle: "AI old" }), JSON.stringify({ type: "ai-title", aiTitle: "AI new" })]), "AI new");
});

test("an empty title record falls through to the next source", async () => {
  assert.equal(await proposed([user("First message"), JSON.stringify({ type: "custom-title", customTitle: "   " })]), "First message");
});

test("corrupt lines are tolerated", async () => {
  assert.equal(await proposed(["{not json", user("Still works"), "[]"]), "Still works");
});

test("a missing file gives null", async () => {
  assert.equal(await proposeTitle(join(tmpdir(), "t3sm-no-such-file.jsonl"), { maxLength: 80 }), null);
});

test("isTechnicalTitle: tags, external blocks, caveats and tag-only text", () => {
  for (const t of [
    "<command-name>/model</command-name>", "<ide_opened_file>The user opened…", "[external unsupported block: image]",
    "Caveat: The messages below", "  <x>  ", "", "   ", "<a></a> <b/>",
  ]) assert.equal(isTechnicalTitle(t), true, t);
  for (const t of ["Fix the login", "Use <div> in React", "External API notes", "Caveats of the design"]) assert.equal(isTechnicalTitle(t), false, t);
});
